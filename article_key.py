"""Канонічний ключ артикула — ЛИШЕ для зіставлення, ніколи для зберігання.

У прайсі частина артикулів набрана з кириличними двійниками латинських літер:
«Cr6сustom-220» має кириличну с (U+0441), «Cr5Р-180» — кириличну Р (U+0420),
«Cr7 mіx-220» — кириличну і (U+0456). Такі рядки виглядають однаково, але не
дорівнюють одне одному, тож звичайний пошук по артикулу мовчки нічого не
знаходить.

canon() зводить рядок до спільного вигляду: NFKC → кирилиця-двійник у латиницю
→ ВЕРХНІЙ регістр → без пробілів по краях. Ключ застосовуємо з ОБОХ боків
кожного зіставлення (каталог, «Залишки дропшиперів», «Назви товарів»,
рядки замовлень) — нормалізувати лише один бік гірше, ніж не нормалізувати
взагалі.

Зберігати ж і показувати треба ОРИГІНАЛЬНИЙ рядок із прайсу: саме його знають
фабрика та прайс, він іде в таблицю замовлень, в опис ТТН і в експорт.

Перед увімкненням перевірено, що жодні два різні артикули прайсу не дають
однакового ключа (296 рядків → 296 ключів).
"""
import unicodedata

# кирилиця → латинський двійник (тільки візуально однакові пари)
HOMOGLYPHS = {
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "О": "O",
    "Р": "P", "С": "C", "Т": "T", "Х": "X", "І": "I", "Ј": "J", "Ѕ": "S",
    "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x",
    "і": "i", "ј": "j", "ѕ": "s",
}


def canon(article) -> str:
    """Ключ для пошуку. Порожній рядок — якщо артикула немає."""
    if not article:
        return ""
    s = unicodedata.normalize("NFKC", str(article))
    s = "".join(HOMOGLYPHS.get(ch, ch) for ch in s)
    return s.upper().strip()


def collisions(articles) -> dict:
    """{ключ: [різні оригінали]} — різні артикули з однаковим ключем.

    Порожньо = ключ нікого не склеює. Використовується у перевірці при старті:
    якщо колізія з'явиться після оновлення прайсу, її має бути видно.
    """
    groups: dict[str, list] = {}
    for a in articles:
        if a:
            groups.setdefault(canon(a), [])
            if a not in groups[canon(a)]:
                groups[canon(a)].append(a)
    return {k: v for k, v in groups.items() if len(v) > 1}
